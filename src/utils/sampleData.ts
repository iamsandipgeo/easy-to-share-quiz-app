/**
 * Generate 100 benchmark MCQs programmatically for testing scale
 */
export function generate100BenchmarkQuestions(): string {
  const categories = [
    { cat: 'বিজ্ঞান ও প্রযুক্তি', code: 'SCI' },
    { cat: 'ইতিহাস ও ঐতিহ্য', code: 'HIST' },
    { cat: 'ভূগোল ও পরিবেশ', code: 'GEO' },
    { cat: 'সাধারণ জ্ঞান', code: 'GK' },
  ];

  let output = '';

  for (let i = 1; i <= 100; i++) {
    const cat = categories[i % categories.length];
    const correctLetter = ['A', 'B', 'C', 'D'][(i - 1) % 4];
    output += `প্রশ্ন ${i}. [${cat.cat}] প্রশ্ন নং ${i}: নিম্নের কোনটি নমুনা পরীক্ষার জন্য প্রস্তুতকৃত সঠিক পরিমাপ বা তথ্য নির্দেশ করে?
A) অপশন ক (${cat.code}-${i}-১)
B) অপশন খ (${cat.code}-${i}-২)
C) অপশন গ (${cat.code}-${i}-৩)
D) অপশন ঘ (${cat.code}-${i}-৪)
সঠিক উত্তর: ${correctLetter}
ব্যাখ্যা: এটি প্রশ্ন নং ${i}-এর আদর্শ ব্যাখ্যা। সঠিক উত্তর ছিল অপশন ${correctLetter}।

`;
  }

  return output.trim();
}
